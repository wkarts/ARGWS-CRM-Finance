"""Native settings upload and tenant branding; real multipart POST, no shared file writes."""
import re,time,zlib,struct,http.client
from html.parser import HTMLParser
from urllib.parse import urlsplit,parse_qs

def run(req,sql,DB,entry,host):
 n=0
 def check(ok,label):
  nonlocal n
  assert ok,label
  n+=1;print('PASS branding '+label,flush=True)
 code,html,_=req('/admin/multiempresa');check(code==200 and 'pme-managed-header' in html and 'tenant.css' in html,'primary administration also loads scoped header styling')
 code,html,_=req(entry+'admin/settings?group=general');check(code==200,'native general settings opens')
 token=re.search(r'name="csrf_token_name"[^>]*value="([^"]+)"',html);assert token
 svg=b'<svg xmlns="http://www.w3.org/2000/svg" width="120" height="32"><rect width="120" height="32" fill="#35465c"/><text x="8" y="22" fill="white">Empresa Alfa</text></svg>'
 dark=svg.replace(b'#35465c',b'#20252d')
 def png_pixel(rgb):
  def chunk(kind,body):return struct.pack('>I',len(body))+kind+body+struct.pack('>I',zlib.crc32(kind+body)&0xffffffff)
  return b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('>IIBBBBB',1,1,8,2,0,0,0))+chunk(b'IDAT',zlib.compress(b'\0'+bytes(rgb)))+chunk(b'IEND',b'')
 png=png_pixel((0,90,180))
 boundary='pme-native-branding-122';parts=[]
 for key,value in [('csrf_token_name',token[1]),('settings[companyname]','Empresa Alfa')]:
  parts.append(('--'+boundary+'\r\nContent-Disposition: form-data; name="'+key+'"\r\n\r\n'+value+'\r\n').encode())
 for key,filename,mime,body in [('company_logo','light.svg','image/svg+xml',svg),('company_logo_dark','dark.svg','image/svg+xml',dark),('favicon','favicon.png','image/png',png)]:
  parts.append(('--'+boundary+'\r\nContent-Disposition: form-data; name="'+key+'"; filename="'+filename+'"\r\nContent-Type: '+mime+'\r\n\r\n').encode()+body+b'\r\n')
 parts.append(('--'+boundary+'--\r\n').encode())
 start=time.monotonic();code,html,_=req(entry+'admin/settings?group=general',b''.join(parts),{'Content-Type':'multipart/form-data; boundary='+boundary});check(code==200,'three branding uploads accepted via native settings')
 print('MEASURE branding settings POST %.3fs'%(time.monotonic()-start),flush=True)
 code,html,_=req(entry+'admin/settings?group=general');check(code==200 and 'pme-tenant' in html and 'tenant.css' in html,'settings and scoped sticky header remain available after saving')
 for name,data in [('company_logo',svg),('company_logo_dark',dark),('favicon',png)]:
  filename=sql("SELECT value FROM `"+DB+"_alfa`.emp_options WHERE name='"+name+"'")
  check(bool(filename),'stored '+name)
  code,content,_=req(entry+'uploads/company/'+filename);check(code==200,'branding served '+name+' '+str(code))
  if name!='favicon':check(content==data.decode(),'correct SVG content '+name)
  check(not (host/'uploads/company'/filename).exists(),'principal uploads untouched '+name)
  check(sql("SELECT value FROM `"+DB+"_beta`.emp_options WHERE name='"+name+"'")=='' ,'other company branding unchanged '+name)
 # Read actual URLs generated by the Settings view and the favicon asset helper.
 class Images(HTMLParser):
  def __init__(self):super().__init__();self.urls=[]
  def handle_starttag(self,tag,attrs):
   a=dict(attrs)
   if tag=='img' and a.get('src'):self.urls.append(a['src'])
   if tag=='link' and 'icon' in a.get('rel','') and a.get('href'):self.urls.append(a['href'])
 def branding_urls(page):
  parser=Images();parser.feed(page)
  return set(u for u in parser.urls if '/uploads/company/' in u or '/__pme/branding' in u)
 urls=branding_urls(html);check(len(urls)>=3,'native HTML contains both logos and favicon')
 flag=host.parent/'static-images';flag.touch()
 try:
  code,_,_=req(entry+'uploads/company/'+sql("SELECT value FROM `"+DB+"_alfa`.emp_options WHERE name='favicon'"))
  check(code==404,'static server reproduces missing image before native PHP entry')
  for image_url in sorted(urls):
   code,content,_=req(image_url)
   check(code==200,'actual Settings image URL survives static server: '+urlsplit(image_url).path)
   parsed=urlsplit(image_url);params=parse_qs(parsed.query);name=params.get('file',[''])[0]
   check(parsed.path.endswith('/__pme/branding'),'native URL avoids static image extension')
   expected=png if name=='favicon.png' else (dark if 'logo_dark' in name else None)
   if name!='favicon.png':expected=dark if name==sql("SELECT value FROM `"+DB+"_alfa`.emp_options WHERE name='company_logo_dark'") else svg
   check(content==expected.decode(errors='replace'),'exact stored image bytes from generated URL')
  favicon_url=next(u for u in urls if parse_qs(urlsplit(u).query).get('file')==['favicon.png'])
  parsed=urlsplit(favicon_url);conn=http.client.HTTPConnection(parsed.hostname,parsed.port,timeout=15)
  try:
   conn.request('GET',parsed.path+'?'+parsed.query);r=conn.getresponse();body=r.read()
   check(r.status==200 and body==png and r.getheader('Content-Type')=='image/png','favicon loads without an administrator session')
   check('no-cache' in r.getheader('Cache-Control',''),'branding is revalidated instead of retaining stale browser cache')
   conn.request('HEAD',parsed.path+'?'+parsed.query);r=conn.getresponse()
   check(r.status==200 and int(r.getheader('Content-Length'))==len(png) and r.read()==b'','HEAD returns image metadata without a response body')
  finally:conn.close()
  beta='/'+sql("SELECT route_key FROM core_multiempresa_routes WHERE target_id=(SELECT id FROM core_multiempresa_companies WHERE slug='beta')")+'/'
  code,_,_=req(beta+'__pme/branding?file=favicon.png');check(code==404,'same image name cannot expose another company upload')
  for query in ['file=../favicon.png','file=%2Fetc%2Fpasswd','file[]=favicon.png','file=..%5Cfavicon.png','file=%00favicon.png']:
   code,_,_=req(entry+'__pme/branding?'+query);check(code==400,'malformed filename rejected '+query)
  code,_,_=req(entry+'__pme/branding?file=missing.png');check(code==404,'missing image does not return a login page or native HTML')
  code,_,_=req(entry+'__pme/branding?file=favicon.png',{'file':'favicon.png'});check(code==405,'branding endpoint cannot mutate uploads')
  # Replace the fixed favicon filename and prove the HTML changes its content version.
  fresh=re.search(r'name="csrf_token_name"[^>]*value="([^"]+)"',html)[1];changed=png_pixel((220,40,10))
  replacement=('--'+boundary+'\r\nContent-Disposition: form-data; name="csrf_token_name"\r\n\r\n'+fresh+'\r\n--'+boundary+'\r\nContent-Disposition: form-data; name="settings[companyname]"\r\n\r\nEmpresa Alfa\r\n--'+boundary+'\r\nContent-Disposition: form-data; name="favicon"; filename="favicon.png"\r\nContent-Type: image/png\r\n\r\n').encode()+changed+('\r\n--'+boundary+'--\r\n').encode()
  code,html,_=req(entry+'admin/settings?group=general',replacement,{'Content-Type':'multipart/form-data; boundary='+boundary})
  check(code==200,'native favicon replacement completes with static-image interception')
  code,html,_=req(entry+'admin/settings?group=general');check(code==200,'Settings refresh reloads the updated favicon URL')
  current=next(u for u in branding_urls(html) if parse_qs(urlsplit(u).query).get('file')==['favicon.png'])
  check(current!=favicon_url,'replacing the same favicon filename changes the generated cache version')
  code,body,_=req(current);check(code==200 and body==changed.decode(errors='replace'),'new favicon content is served immediately')
  code,html,_=req(entry+'authentication/login');check(code==200 and branding_urls(html),'customer login renders company branding without an administrator route')
  for image_url in branding_urls(html):
   code,_,_=req(image_url);check(code==200,'customer login branding also survives static interception')

 finally:flag.unlink()
 for route in ['admin','admin/staff','admin/clients','admin/settings?group=general']:
  code,html,_=req(entry+route);check(code==200 and 'id="header"' in html and 'pme-tenant' in html,'header and navigation '+route)
 print('RESULT %d native branding assertions passed'%n,flush=True)
